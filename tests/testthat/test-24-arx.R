testthat::test_that("arx estimation of ARDL(4,4) with saturation = NULL works", {

  # used to fail because of saturation = NULL and not enough df for ARDL(4,4)
  # so arx() was failing and not returning a model object
  # now arx() is wrapped in try()
  expect_silent(test <- run_model(specification = spec,
                                  input = dat %>%
                                    tidyr::pivot_longer(-time,names_to = "na_item", values_to = "values"),
                                  dictionary = dict_new,
                                  saturation = NULL,
                                  quiet = TRUE,
                                  plot = FALSE,

                                  primary_source = "local",
                                  constrain.to.minimum.sample = FALSE,

                                  ardl_or_ecm = "ecm",
                                  ecm_pretest = "auto"))


  expect_identical(round(test$module_collection$model[[1]]$logl,4),32.0772)
  expect_identical(round(test$module_collection$model[[1]]$coef,4),c(0.3709, 0.6604, -0.4387, -1.6359))
  expect_identical(names(coef(test$module_collection$model[[1]])),c("mconst", "q_2", "q_3", "q_4"))

})
